import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { PaymentMethod } from '@prisma/client';
import { Transform, Type } from 'class-transformer';
import {
  IsDateString,
  IsEnum,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsPositive,
  IsString,
  Max,
  Min,
} from 'class-validator';
import {
  MAX_SAFE_WHOLE_RUPEE,
  parseStrictWholeRupeeValue,
} from '../../common/utils/whole-rupee.util';

export class RecordCollectionDto {
  @ApiProperty({
    example: '2351d319-24f1-48dd-8a9d-657fbf2d371f',
    description: 'UUID of the subscriber ticket receiving the collection',
  })
  @IsNotEmpty({ message: 'Ticket ID is required' })
  @IsString()
  ticketId: string;

  @ApiProperty({
    example: 4,
    description: 'Installment month number (1 to N) being collected',
  })
  @IsNotEmpty({ message: 'Installment month is required' })
  @Type(() => Number)
  @IsInt()
  @Min(1)
  installmentMonth: number;

  @ApiProperty({
    type: 'integer',
    example: 3950,
    description:
      'Exact net installment amount in whole integer Rupees (must identically match due.netPayableAmount)',
  })
  @IsNotEmpty({ message: 'Collection amount is required' })
  @Transform(({ value }) => parseStrictWholeRupeeValue(value))
  @IsInt({ message: 'Collection amount must be a whole Rupee integer amount (zero paise/decimals)' })
  @IsPositive({ message: 'Collection amount must be a positive whole number' })
  @Max(MAX_SAFE_WHOLE_RUPEE, {
    message: 'Collection amount exceeds maximum safe whole-Rupee integer limit',
  })
  amount: number;

  @ApiProperty({
    enum: PaymentMethod,
    example: PaymentMethod.CASH,
    description: 'Payment method (CASH, UPI, CHEQUE, BANK_TRANSFER)',
  })
  @IsNotEmpty({ message: 'Payment method is required' })
  @IsEnum(PaymentMethod)
  paymentMethod: PaymentMethod;

  @ApiPropertyOptional({
    example: 'd9b2d63d-a232-4e45-814a-5f0962858b29',
    description:
      'Unique UUID generated by mobile app at point of physical collection for offline sync deduplication',
  })
  @IsOptional()
  @IsString()
  idempotencyKey?: string;

  @ApiPropertyOptional({
    example: 'UPI/20261018/9876543210',
    description:
      'Optional transaction reference (UPI UTR number, Cheque number, or Bank transfer reference)',
  })
  @IsOptional()
  @IsString()
  transactionRef?: string;

  @ApiPropertyOptional({
    example: '2026-10-18T10:30:00.000Z',
    description:
      'Device timestamp when physical collection was recorded in the field',
  })
  @IsOptional()
  @IsDateString()
  collectedAt?: string;
}
