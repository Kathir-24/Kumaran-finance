import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsOptional, IsString, Matches } from 'class-validator';
import { REGEX_TOTP_CODE } from '../../common/constants';

export class TotpEnableDto {
  @ApiProperty({
    example: 'JBSWY3DPEHPK3PXP',
    description: 'Base32 secret key received from /auth/totp/setup',
  })
  @IsNotEmpty({ message: 'Secret key is required' })
  @IsString()
  secret: string;

  @ApiProperty({
    example: '123456',
    description: 'Current 6-digit TOTP code generated by Microsoft Authenticator',
  })
  @IsNotEmpty({ message: 'Verification code is required' })
  @IsString()
  @Matches(REGEX_TOTP_CODE, { message: 'Code must be exactly 6 digits' })
  code: string;

  @ApiProperty({
    example: 'AdminPass#2026!',
    description: 'Current account password. Required strictly when replacing an already-configured TOTP 2FA factor.',
    required: false,
  })
  @IsOptional()
  @IsString()
  password?: string;
}
