import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Matches } from 'class-validator';

export class TotpVerifyDto {
  @ApiProperty({
    example: 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9...',
    description: 'Temporary session token returned from /auth/web/login when TOTP 2FA is required',
  })
  @IsNotEmpty({ message: 'Temporary session token is required' })
  @IsString()
  tempToken: string;

  @ApiProperty({
    example: '492817',
    description: '6-digit rotating TOTP code generated by Microsoft Authenticator',
  })
  @IsNotEmpty({ message: 'TOTP code is required' })
  @IsString()
  @Matches(/^\d{6}$/, { message: 'TOTP code must be exactly 6 digits' })
  totpCode: string;
}
